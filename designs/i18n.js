export function initI18n(defaultLang = 'sv') {
  const apply = (lang) => {
    const copy = translations[lang];
    if (!copy) return;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const v = copy[el.dataset.i18n];
      if (v != null) el.textContent = v;
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const v = copy[el.dataset.i18nHtml];
      if (v != null) el.innerHTML = v;
    });
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-lang]').forEach((b) => {
      const on = b.dataset.lang === lang;
      b.classList.toggle('is-active', on);
      b.setAttribute('aria-pressed', String(on));
    });
    try { localStorage.setItem('radi-language', lang); } catch (e) {}
  };
  document.querySelectorAll('[data-lang]').forEach((b) => {
    b.addEventListener('click', () => apply(b.dataset.lang));
  });
  let start = defaultLang;
  try { start = localStorage.getItem('radi-language') || defaultLang; } catch (e) {}
  apply(start);
  return apply;
}
