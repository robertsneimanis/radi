function applyLanguage(language) {
  const copy = translations[language];
  if (!copy) return;
  Object.entries(textTargets).forEach(([key, selector]) => {
    const element = document.querySelector(selector);
    if (element) element.innerHTML = copy[key];
  });
  document.documentElement.lang = language;
  document.querySelectorAll('.language-button').forEach((button) => {
    button.classList.toggle('is-active', button.dataset.language === language);
    button.setAttribute('aria-pressed', button.dataset.language === language);
  });
  localStorage.setItem('radi-language', language);
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.language-button').forEach((button) => {
    button.addEventListener('click', () => applyLanguage(button.dataset.language));
  });
  applyLanguage(localStorage.getItem('radi-language') || 'sv');
});
